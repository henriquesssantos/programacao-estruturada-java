public class exemploFormato{
    
    public static void main(String [] args){
        int valorInteiro = 42;
        double valorReal = 3.14159;
        char caractere = 'A';
        String cadeiaDeCaracteres = "hello world!";
        boolean valorLogico = true;
        
        System.out.printf("Valor inteiro: %d\n", valorInteiro);
        System.out.printf("Valor real: %8.2f\n", valorReal);
        System.out.printf("valor caractere: %c\n", caractere);
        System.out.printf("valor cadeia de caracteres %s\n:", cadeiaDeCaracteres);
        System.out.printf("Valor boleano %b\n", valorLogico);
        
        
        
        
    }
}